import { NextResponse } from "next/server";
import {
  findJonotaOrder,
  getPublicBaseUrl,
  isJonotaPayConfigured,
  recordJonotaVerification,
  recordUnconfirmedTransaction,
  verifyJonotaTransaction,
} from "@/lib/jonota-pay";

/**
 * GET /api/payments/jonota/callback/{orderId}
 *
 * The customer is redirected here by the payment gateway after paying.
 * A redirect is NEVER treated as proof of payment: we take the transaction id
 * from the redirect, call the provider's verification API, and only then apply
 * the result. The customer is always sent to our own result page - no provider
 * supplied `status` value is trusted or forwarded.
 *
 * The route is intentionally public (the gateway cannot send a session cookie)
 * but it can only ever affect the order whose transaction id was verified.
 */

const TX_KEYS = [
  "transaction_id",
  "transactionId",
  "txn_id",
  "txn",
  "trx_id",
  "payment_id",
  "paymentId",
];

const ORDER_KEYS = ["order_id", "orderId", "order", "order_number", "orderNumber"];

function firstParam(searchParams, keys) {
  for (const key of keys) {
    const value = searchParams.get(key);
    if (value && String(value).trim()) return String(value).trim();
  }
  return "";
}

export async function GET(request, ctx) {
  const base = getPublicBaseUrl(request);
  const { searchParams } = request.nextUrl;
  const params = (await ctx?.params) || {};
  const pathOrder = Array.isArray(params.orderId)
    ? params.orderId.filter(Boolean).join("/")
    : params.orderId;

  const orderRef = String(pathOrder || firstParam(searchParams, ORDER_KEYS) || "").trim();
  const transactionId = firstParam(searchParams, TX_KEYS);

  let order = null;
  try {
    order = await findJonotaOrder({
      orderId: orderRef || undefined,
      transactionId: transactionId || undefined,
    });
  } catch (error) {
    console.error("[jonota] callback order lookup failed:", error.message);
  }

  if (order && transactionId && isJonotaPayConfigured()) {
    let verification = null;
    try {
      verification = await verifyJonotaTransaction(transactionId);
      await recordJonotaVerification({
        order,
        verification,
        source: "gateway-callback",
      });
    } catch (error) {
      /* The customer may still be charged. Do not fail the redirect - the
       * result page will offer a re-verify and support can check manually.
       * Store the transaction id as "unconfirmed" so a later verification can
       * still match it to this order without trusting the redirect. */
      console.error(
        "[jonota] callback verification failed:",
        error?.code || "",
        error.message
      );

      const transient =
        error?.code === "PAYMENT_GATEWAY_UNAVAILABLE" ||
        error?.code === "PAYMENT_VERIFY_TIMEOUT" ||
        error?.code === "PAYMENT_VERIFY_INVALID_RESPONSE";

      /* The gateway verified the transaction but did not return an order
       * reference. Our callback path is generated by this server, so it is
       * safe to remember the transaction as unconfirmed; an admin can then
       * re-verify it (amount and uniqueness are still enforced). */
      const verifiedButUnmatched =
        error?.code === "PAYMENT_ORDER_REFERENCE_MISSING" &&
        verification &&
        (verification.status === "COMPLETED" || verification.status === "PENDING");

      if (transient || verifiedButUnmatched) {
        try {
          await recordUnconfirmedTransaction({
            order,
            transactionId,
            source: "gateway-callback",
            reason: verifiedButUnmatched
              ? "The gateway verified this transaction but did not return the order reference. An administrator must review it."
              : "The payment gateway could not be reached or did not confirm this transaction yet.",
          });
        } catch (recordError) {
          console.error("[jonota] could not store unconfirmed transaction:", recordError.message);
        }
      }
    }
  }

  const target = new URL(`${base}/payment/${order ? "success" : "verify"}`);
  if (order?.orderNumber) {
    target.searchParams.set("orderId", order.orderNumber);
    if (transactionId) target.searchParams.set("txn", transactionId);
  } else if (orderRef) {
    target.searchParams.set("order", orderRef);
  } else {
    target.searchParams.set("unmatched", "1");
  }

  return NextResponse.redirect(target, { status: 303 });
}
